  0x790200b8 0x790200bc 0x790200c0 0x790200c4 \
  0x79020400 0x79020404 0x79020408 0x79020418 \
  0x79020420 0x79020424 0x79020428 \
  0x79020440 0x79020444 0x79020448 0x79020458 \
  0x79020480 0x79020484 0x79020488 0x79020498 \
  0x790204c0 0x790204c4 0x790204c8 0x790204d8 \
  0x79024000 0x79024004 0x7c400000 0x7c400400 0x7c420000; do
